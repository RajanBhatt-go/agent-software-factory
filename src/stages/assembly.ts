// ─────────────────────────────────────────────────────────────
//  Agent Software Factory — Stage 7: Assembly
//  Writes all pipeline outputs into markdown files.
// ─────────────────────────────────────────────────────────────

import { writeFile, mkdir, getOutputDir } from "../lib/io.js";
import { FactoryContext } from "../lib/types.js";

function fmtTime(ms: number): string {
  if (ms < 1000) return `${ms}ms`;
  return `${(ms / 1000).toFixed(1)}s`;
}

function fmtCost(cost: number): string {
  if (cost < 0.01) return `$${(cost * 100).toFixed(2)}¢`;
  return `$${cost.toFixed(4)}`;
}

export async function stageAssembly(
  ctx: FactoryContext,
  timings: Record<string, { durationMs: number; cost: number; model: string }>
): Promise<void> {
  const outputDir = getOutputDir(process.cwd());
  await mkdir(outputDir, { recursive: true });

  // ── Generate all documents ──────────────────────────────

  const docs: Array<{ name: string; content: string }> = [
    { name: "SPEC.md",         content: buildSpecDoc(ctx) },
    { name: "TEST_CASES.md",   content: buildTestCasesDoc(ctx) },
    { name: "UX_WORKFLOW.md",  content: buildUXDoc(ctx) },
    { name: "SECURITY_REVIEW.md", content: buildSecurityDoc(ctx) },
    { name: "ALGORITHM_REVIEW.md", content: buildAlgorithmDoc(ctx) },
  ];

  // ── Write each file ─────────────────────────────────────

  for (const doc of docs) {
    await writeFile(`${outputDir}/${doc.name}`, doc.content);
  }

  // ── Write pipeline summary ──────────────────────────────

  await writeFile(`${outputDir}/pipeline-summary.md`, buildSummary(ctx, timings));

  console.log(`\n✅ Documents written to ${outputDir}/`);
  for (const doc of docs) {
    console.log(`   📄 ${doc.name}`);
  }
  console.log(`   📄 pipeline-summary.md`);
  console.log("");
}

// ── Document builders ────────────────────────────────────

function buildSpecDoc(ctx: FactoryContext): string {
  const s = ctx.spec;
  if (!s) return "# SPEC\n\n*No spec was generated.*\n";

  let md = `# ${s.title}\n\n`;
  md += `${s.overview}\n\n`;

  if (s.functionalRequirements.length > 0) {
    md += `## Functional Requirements\n\n`;
    for (const r of s.functionalRequirements) {
      const p = r.priority === "must" ? "🔴" : r.priority === "should" ? "🟡" : r.priority === "could" ? "🟢" : "⚪";
      md += `- ${p} **${r.id}**: ${r.description}\n`;
    }
    md += "\n";
  }

  if (s.nonFunctionalRequirements.length > 0) {
    md += `## Non-Functional Requirements\n\n`;
    for (const r of s.nonFunctionalRequirements) {
      md += `- **${r.id}**: ${r.description} _(priority: ${r.priority})_\n`;
    }
    md += "\n";
  }

  if (s.acceptanceCriteria.length > 0) {
    md += `## Acceptance Criteria\n\n`;
    for (const c of s.acceptanceCriteria) {
      md += `- [ ] ${c}\n`;
    }
    md += "\n";
  }

  if (s.components.length > 0) {
    md += `## Components\n\n`;
    for (const c of s.components) {
      md += `### ${c.name}\n`;
      md += `${c.description}\n\n`;
      if (c.technology) md += `- **Technology:** ${c.technology}\n`;
      if (c.interactions.length > 0) {
        md += `- **Interactions:**\n`;
        for (const i of c.interactions) md += `  - ${i}\n`;
      }
      md += "\n";
    }
  }

  if (s.dataModel) {
    md += `## Data Model\n\n`;
    for (const e of s.dataModel.entities) {
      md += `### ${e.name}\n`;
      md += `${e.description}\n\n`;
      md += "| Field |\n|-------|\n";
      for (const f of e.fields) md += `| ${f} |\n`;
      md += "\n";
    }
    if (s.dataModel.relationships.length > 0) {
      md += `### Relationships\n\n`;
      for (const r of s.dataModel.relationships) md += `- ${r}\n`;
      md += "\n";
    }
  }

  md += `---\n*Generated by Agent Software Factory*\n`;
  return md;
}

function buildTestCasesDoc(ctx: FactoryContext): string {
  const tests = ctx.testCases;
  if (!tests || tests.length === 0) return "# Test Cases\n\n*No test cases were generated.*\n";

  const byType: Record<string, typeof tests> = {};
  for (const t of tests) {
    (byType[t.type] ??= []).push(t);
  }

  let md = `# Test Cases\n\n${tests.length} test cases generated.\n\n`;
  md += `| Type | Count |\n|------|-------|\n`;

  for (const [type, cases] of Object.entries(byType)) {
    md += `| ${type} | ${cases.length} |\n`;
  }
  md += "\n---\n\n";

  for (const [type, cases] of Object.entries(byType)) {
    md += `## ${type.charAt(0).toUpperCase() + type.slice(1)} Tests\n\n`;
    for (const t of cases) {
      const edge = t.edgeCase ? " ⚠️ Edge Case" : "";
      md += `### ${t.name}${edge}\n\n`;
      md += `- **Scenario:** ${t.scenario}\n`;
      md += `- **Given:** ${t.given}\n`;
      md += `- **When:** ${t.when}\n`;
      md += `- **Then:** ${t.then}\n\n`;
    }
  }

  md += `---\n*Generated by Agent Software Factory*\n`;
  return md;
}

function buildUXDoc(ctx: FactoryContext): string {
  const ux = ctx.uxWorkflow;
  if (!ux) return "# UX Workflow\n\n*No UX workflow was generated.*\n";

  let md = `# UX Workflow\n\n`;

  if (ux.userFlows.length > 0) {
    md += `## User Flows\n\n`;
    for (const flow of ux.userFlows) {
      md += `### ${flow.actor}: ${flow.description}\n\n`;
      md += "| Step | Action | Expected Outcome |\n|------|--------|------------------|\n";
      for (const step of flow.steps) {
        md += `| ${step.step} | ${step.action} | ${step.expectedOutcome} |\n`;
      }
      md += "\n";
    }
  }

  if (ux.states.length > 0) {
    md += `## States\n\n`;
    for (const s of ux.states) md += `- \`${s}\`\n`;
    md += "\n";
  }

  if (ux.uiComponents.length > 0) {
    md += `## UI Components\n\n`;
    md += "| Component | Type | Description |\n|-----------|------|-------------|\n";
    for (const c of ux.uiComponents) {
      md += `| ${c.name} | ${c.type} | ${c.description} |\n`;
    }
    md += "\n";
  }

  if (ux.decisions.length > 0) {
    md += `## UX Decisions\n\n`;
    for (const d of ux.decisions) md += `- ${d}\n`;
    md += "\n";
  }

  if (ux.notes.length > 0) {
    md += `## Notes & Open Questions\n\n`;
    for (const n of ux.notes) md += `- ${n}\n`;
    md += "\n";
  }

  md += `---\n*Generated by Agent Software Factory*\n`;
  return md;
}

function buildSecurityDoc(ctx: FactoryContext): string {
  const sec = ctx.securityReview;
  if (!sec) return "# Security Review\n\n*No security review was generated.*\n";

  let md = `# Security Review\n\n`;
  md += `**Overall Risk Level:** ${riskBadge(sec.overallRisk)}\n\n`;

  if (sec.threatModel.length > 0) {
    md += `## Threat Model (STRIDE)\n\n`;
    md += "| ID | Category | Risk | Component | Description |\n|----|----------|------|-----------|-------------|\n";
    for (const t of sec.threatModel) {
      md += `| ${t.id} | ${t.category} | ${riskBadge(t.risk)} | ${t.affectedComponent} | ${t.description} |\n`;
    }
    md += "\n";
  }

  if (sec.mitigations.length > 0) {
    md += `## Mitigations\n\n`;
    md += "| Threat | Mitigation | Effort |\n|--------|------------|--------|\n";
    for (const m of sec.mitigations) {
      md += `| ${m.threatId} | ${m.description} | ${effortBadge(m.effort)} |\n`;
    }
    md += "\n";
  }

  if (sec.recommendations.length > 0) {
    md += `## Recommendations\n\n`;
    for (const r of sec.recommendations) md += `- ${r}\n`;
    md += "\n";
  }

  if (sec.compliance.length > 0) {
    md += `## Compliance Implications\n\n`;
    for (const c of sec.compliance) md += `- ${c}\n`;
    md += "\n";
  }

  md += `---\n*Generated by Agent Software Factory*\n`;
  return md;
}

function buildAlgorithmDoc(ctx: FactoryContext): string {
  const algo = ctx.algorithmReview;
  if (!algo) return "# Algorithm Review\n\n*No algorithm review was generated.*\n";

  let md = `# Algorithm Review\n\n`;

  if (algo.complexityAnalysis.length > 0) {
    md += `## Complexity Analysis\n\n`;
    md += "| Time | Space | Explanation |\n|------|-------|-------------|\n";
    for (const c of algo.complexityAnalysis) {
      md += `| \`${c.timeComplexity}\` | \`${c.spaceComplexity}\` | ${c.explanation} |\n`;
    }
    md += "\n";
  }

  if (algo.alternatives.length > 0) {
    md += `## Alternatives Considered\n\n`;
    for (const alt of algo.alternatives) {
      md += `### ${alt.name}\n`;
      md += `${alt.description}\n\n`;
      if (alt.pros.length > 0) {
        md += "**Pros:**\n";
        for (const p of alt.pros) md += `- ✅ ${p}\n`;
      }
      if (alt.cons.length > 0) {
        md += "**Cons:**\n";
        for (const c of alt.cons) md += `- ❌ ${c}\n`;
      }
      md += "\n";
    }
  }

  if (algo.recommendation) {
    md += `## Recommendation\n\n${algo.recommendation}\n\n`;
  }

  if (algo.performanceConsiderations.length > 0) {
    md += `## Performance Considerations\n\n`;
    for (const p of algo.performanceConsiderations) md += `- ${p}\n`;
    md += "\n";
  }

  md += `---\n*Generated by Agent Software Factory*\n`;
  return md;
}

function buildSummary(ctx: FactoryContext, timings: Record<string, { durationMs: number; cost: number; model: string }>): string {
  const totalDuration = Object.values(timings).reduce((s, t) => s + t.durationMs, 0);
  const totalCost = Object.values(timings).reduce((s, t) => s + t.cost, 0);

  let md = `# Pipeline Summary\n\n`;
  md += `**Feature:** ${ctx.feature.title}\n\n`;

  md += `| Stage | Model | Duration | Cost |\n|-------|-------|----------|------|\n`;
  for (const [stage, timing] of Object.entries(timings)) {
    md += `| ${stage} | ${timing.model.split("/").pop() ?? timing.model} | ${fmtTime(timing.durationMs)} | ${fmtCost(timing.cost)} |\n`;
  }
  md += `| **Total** | | **${fmtTime(totalDuration)}** | **${fmtCost(totalCost)}** |\n\n`;

  md += `## Generated Documents\n\n`;
  md += `- [SPEC.md](./SPEC.md)\n`;
  md += `- [TEST_CASES.md](./TEST_CASES.md)\n`;
  md += `- [UX_WORKFLOW.md](./UX_WORKFLOW.md)\n`;
  md += `- [SECURITY_REVIEW.md](./SECURITY_REVIEW.md)\n`;
  md += `- [ALGORITHM_REVIEW.md](./ALGORITHM_REVIEW.md)\n`;

  return md;
}

function riskBadge(risk: string): string {
  switch (risk) {
    case "critical": return "🔴 Critical";
    case "high":     return "🟠 High";
    case "medium":   return "🟡 Medium";
    case "low":      return "🟢 Low";
    default:         return risk;
  }
}

function effortBadge(effort: string): string {
  switch (effort) {
    case "low":    return "🟢 Low";
    case "medium": return "🟡 Medium";
    case "high":   return "🔴 High";
    default:       return effort;
  }
}